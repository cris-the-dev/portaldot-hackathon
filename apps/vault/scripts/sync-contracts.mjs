// Generates src/generated/{abis,deployments}.ts from the Foundry build output and
// config/deployments/<chainId>.json (written by contracts/script/Deploy.s.sol on --broadcast).
// ABIs are only regenerated when contracts/out exists (run `forge build`); the committed copy is kept otherwise.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../../..");
const outDir = path.join(root, "contracts/out");
const deploymentsDir = path.join(root, "config/deployments");
const genDir = path.resolve(import.meta.dirname, "../src/generated");
mkdirSync(genDir, { recursive: true });

const header = "// Generated by scripts/sync-contracts.mjs — do not edit.\n";
const write = (file, body) => {
  const target = path.join(genDir, file);
  const content = header + body;
  if (existsSync(target) && readFileSync(target, "utf8") === content) return;
  writeFileSync(target, content);
  console.log(`sync-contracts: wrote src/generated/${file}`);
};

// ABIs
const contracts = { mockRwaAbi: "MockRWA", rwaVaultAbi: "RWAVault" };
if (existsSync(outDir)) {
  let body = "";
  for (const [exportName, contract] of Object.entries(contracts)) {
    const artifact = JSON.parse(readFileSync(path.join(outDir, `${contract}.sol/${contract}.json`), "utf8"));
    body += `\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  }
  write("abis.ts", body);
} else {
  console.log("sync-contracts: contracts/out not found, keeping committed ABIs (run `forge build` to refresh)");
}

// Deployments
const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const file of readdirSync(deploymentsDir).filter((f) => f.endsWith(".json")).sort()) {
    const d = JSON.parse(readFileSync(path.join(deploymentsDir, file), "utf8"));
    for (const field of ["chainId", "MockRWA", "RWAVault", "deployBlock"]) {
      if (!(field in d)) throw new Error(`config/deployments/${file}: missing "${field}"`);
    }
    deployments[d.chainId] = { MockRWA: d.MockRWA, RWAVault: d.RWAVault, deployBlock: d.deployBlock };
  }
}
write(
  "deployments.ts",
  `
export interface Deployment {
  MockRWA: \`0x\${string}\`;
  RWAVault: \`0x\${string}\`;
  deployBlock: number;
}

export const deployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};
`,
);
