// Generates src/generated/{abis,deployments}.ts from ../contracts/out and ../deployments/<chainId>.json.
// ABIs refresh only when contracts are built (`pnpm contracts:build`); the existing file is kept otherwise.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const gen = path.resolve(import.meta.dirname, "../src/generated");
mkdirSync(gen, { recursive: true });
const header = "// Generated by scripts/sync.mjs — do not edit.\n";

// Foundry (contracts/out) or Hardhat (contracts/artifacts) build output.
const artifact = [
  path.join(root, "contracts/out/Counter.sol/Counter.json"),
  path.join(root, "contracts/artifacts/src/Counter.sol/Counter.json"),
].find((f) => existsSync(f));
if (artifact) {
  const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
  writeFileSync(path.join(gen, "abis.ts"), `${header}\nexport const counterAbi = ${JSON.stringify(abi, null, 2)} as const;\n`);
}

const deployments = {};
const dir = path.join(root, "deployments");
if (existsSync(dir)) {
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(path.join(dir, file), "utf8"));
    deployments[d.chainId] = { Counter: d.Counter, deployBlock: d.deployBlock };
  }
}
writeFileSync(
  path.join(gen, "deployments.ts"),
  `${header}\nexport const deployments: Record<number, { Counter: \`0x\${string}\`; deployBlock: number }> = ${JSON.stringify(deployments, null, 2)};\n`,
);
